# Stage = furthest-along track; 'closed' when both tracks ended, or one ended and the
# other never started. Ranks: 0 not started, 1 referral, 2 applied, 3 interview, 4 offer, -1 ended.
JOB_STAGE_OF = """
CREATE FUNCTION app.job_stage_of(d app.direct_status, r app.referral_status)
RETURNS app.job_stage LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  WITH t AS (
    SELECT
      CASE d WHEN 'not_applied'  THEN 0 WHEN 'applied' THEN 2
             WHEN 'interviewing' THEN 3 WHEN 'offer'   THEN 4
             ELSE -1 END AS dr,
      CASE r WHEN 'not_asked' THEN 0
             WHEN 'asked' THEN 1 WHEN 'referred_internally' THEN 1
             WHEN 'referral_link_received' THEN 1
             WHEN 'applied_via_referral' THEN 2 WHEN 'interviewing' THEN 3 WHEN 'offer' THEN 4
             ELSE -1 END AS rr
  )
  SELECT CASE
    WHEN dr <= 0 AND rr <= 0 AND (dr = -1 OR rr = -1) THEN 'closed'
    ELSE (ARRAY['to_do','referral','applied','interview','offer']::app.job_stage[])[
      greatest(dr, rr) + 1]
  END
  FROM t
$$
"""


