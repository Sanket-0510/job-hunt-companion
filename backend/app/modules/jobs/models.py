import enum
import uuid
from datetime import date, datetime

from sqlalchemy import Boolean, CheckConstraint, Computed, Date, Index, Text, func, text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import TZ, Base, pg_enum, user_fk, uuid_pk


class JobPriority(enum.StrEnum):
    # Declaration order is the Postgres sort order: high first.
    high = "high"
    medium = "medium"
    low = "low"


class DirectStatus(enum.StrEnum):
    not_applied = "not_applied"
    applied = "applied"
    interviewing = "interviewing"
    offer = "offer"
    rejected = "rejected"


class ReferralStatus(enum.StrEnum):
    not_asked = "not_asked"
    asked = "asked"
    referred_internally = "referred_internally"
    referral_link_received = "referral_link_received"
    applied_via_referral = "applied_via_referral"
    interviewing = "interviewing"
    offer = "offer"
    rejected = "rejected"
    no_response = "no_response"


class JobStage(enum.StrEnum):
    to_do = "to_do"
    referral = "referral"
    applied = "applied"
    interview = "interview"
    offer = "offer"
    closed = "closed"


# Referral statuses where we are waiting on the contact; drives "which track is waiting".
REFERRAL_WAITING = {
    ReferralStatus.asked,
    ReferralStatus.referred_internally,
    ReferralStatus.referral_link_received,
}

STAGE_SQL = "app.job_stage_of(direct_status, referral_status)"
SEARCH_SQL = (
    "lower(company || ' ' || role || ' ' || coalesce(location, '') || ' ' || "
    "coalesce(notes, '') || ' ' || coalesce(referral_contact, '') || ' ' || "
    "coalesce(source, ''))"
)


class Job(Base):
    __tablename__ = "jobs"
    __table_args__ = (
        CheckConstraint("btrim(company) <> ''", name="company_not_blank"),
        CheckConstraint("btrim(role) <> ''", name="role_not_blank"),
        Index("ix_jobs_user_id_created_at", "user_id", text("created_at DESC")),
        Index("ix_jobs_user_id_date_found", "user_id", text("date_found DESC")),
        # Only jobs that can ever be due: due today, follow-up-due count, digest worker.
        Index(
            "ix_jobs_user_id_due",
            "user_id",
            "follow_up_date",
            postgresql_where=text(
                "follow_up_date IS NOT NULL AND stage NOT IN ('offer', 'closed')"
            ),
        ),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    user_id: Mapped[uuid.UUID] = user_fk()
    company: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    location: Mapped[str | None] = mapped_column(Text)
    experience_asked: Mapped[str | None] = mapped_column(Text)  # free text, e.g. "2-4 yrs"
    apply_url: Mapped[str | None] = mapped_column(Text)
    source: Mapped[str | None] = mapped_column(Text)
    priority: Mapped[JobPriority] = mapped_column(
        pg_enum(JobPriority, "job_priority"), nullable=False, server_default="medium"
    )
    # The API always sends the user-local date; the default is only a fallback.
    date_found: Mapped[date] = mapped_column(
        Date, nullable=False, server_default=func.current_date()
    )
    notes: Mapped[str | None] = mapped_column(Text)
    # Direct apply track
    direct_status: Mapped[DirectStatus] = mapped_column(
        pg_enum(DirectStatus, "direct_status"), nullable=False, server_default="not_applied"
    )
    applied_on: Mapped[date | None] = mapped_column(Date)
    # Referral track
    referral_status: Mapped[ReferralStatus] = mapped_column(
        pg_enum(ReferralStatus, "referral_status"), nullable=False, server_default="not_asked"
    )
    referral_contact: Mapped[str | None] = mapped_column(Text)
    asked_on: Mapped[date | None] = mapped_column(Date)
    # LinkedIn helpers
    company_linkedin_url: Mapped[str | None] = mapped_column(Text)
    recruiter_name: Mapped[str | None] = mapped_column(Text)
    recruiter_linkedin_url: Mapped[str | None] = mapped_column(Text)
    # Follow-up. Snooze moves follow_up_date; snoozed_at only records when.
    follow_up_date: Mapped[date | None] = mapped_column(Date)
    snoozed_at: Mapped[datetime | None] = mapped_column(TZ)
    emails_reversed: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("false")
    )
    # Generated by Postgres, never written by the app.
    stage: Mapped[JobStage] = mapped_column(
        pg_enum(JobStage, "job_stage"), Computed(STAGE_SQL, persisted=True), nullable=False
    )
    search_text: Mapped[str] = mapped_column(
        Text, Computed(SEARCH_SQL, persisted=True), nullable=False
    )
    created_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(TZ, nullable=False, server_default=func.now())

    def is_due(self, user_today: date) -> bool:
        return (
            self.follow_up_date is not None
            and self.follow_up_date <= user_today
            and self.stage not in (JobStage.offer, JobStage.closed)
        )
